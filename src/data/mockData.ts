// Validate Algerian phone numbers
export function validateAlgerianPhone(phone: string): { isValid: boolean; carrier: string; formatted: string; isSuspiciousPattern: boolean } {
  if (!phone) return { isValid: false, carrier: 'غير معروف', formatted: '', isSuspiciousPattern: true };
  const cleaned = phone.replace(/[\s\-\+\(\)]/g, '');
  let standard = cleaned;
  if (standard.startsWith('213')) {
    standard = '0' + standard.slice(3);
  }

  // Check 10 digits starting with 05, 06, 07, 02
  const isValidLength = standard.length === 10;
  const prefix = standard.slice(0, 2);

  let carrier = 'غير معروف';
  if (prefix === '05') carrier = 'Ooredoo (أوريدو)';
  else if (prefix === '06') carrier = 'Mobilis (موبيليس)';
  else if (prefix === '07') carrier = 'Djezzy (جيزي)';
  else if (prefix === '02') carrier = 'خط أرضي ثابت (Algérie Télécom)';

  const isValidPrefix = ['05', '06', '07', '02', '03', '04'].includes(prefix);
  const isValid = isValidLength && isValidPrefix;

  // Check repetitive fake numbers like 0555555555, 0600000000, 0712345678
  const isAllSameDigits = /^0[5-7](\d)\1{7}$/.test(standard);
  const isSequential = standard === '0512345678' || standard === '0612345678' || standard === '0712345678' || standard === '0500000000' || standard === '0600000000' || standard === '0700000000';
  const isSuspiciousPattern = !isValid || isAllSameDigits || isSequential;

  return {
    isValid,
    carrier,
    formatted: standard,
    isSuspiciousPattern,
  };
}

// Smart Fraud Risk Evaluator
export function evaluateOrderFraudRisk(
  order: Order,
  blacklist: BlacklistEntry[] = [],
  allOrders: Order[] = []
): { score: number; level: 'low' | 'medium' | 'high'; reasons: string[]; recommendation: string } {
  let score = 0;
  const reasons: string[] = [];

  const phoneCheck = validateAlgerianPhone(order.phone);
  if (!phoneCheck.isValid) {
    score += 40;
    reasons.push('رقم هاتف غير مطابق لمعايير الاتصالات في الجزائر (10 أرقام)');
  }
  if (phoneCheck.isSuspiciousPattern) {
    score += 35;
    reasons.push('نمط رقم الهاتف مشبوه (أرقام متكررة أو وهمية)');
  }

  // Check Blacklist
  const isBlacklisted = blacklist.some(
    (b) => b.type === 'phone' && (b.value === order.phone || b.value === phoneCheck.formatted)
  );
  if (isBlacklisted) {
    score += 70;
    reasons.push('رقم الهاتف مسجل في القائمة السوداء للمتجر');
  }

  // Check duplicate recent orders
  const duplicates = allOrders.filter(
    (o) => o.id !== order.id && o.phone === order.phone
  );
  if (duplicates.length >= 3) {
    score += 25;
    reasons.push(`الزبون لديه ${duplicates.length} طلبات سابقة تحت نفس الرقم`);
  }

  // High total amount
  if (order.totalAmount > 30000) {
    score += 15;
    reasons.push('قيمة الطلب مرتفعة جداً (تتجاوز 30,000 دج) - يوصى بالتأكيد المباشر');
  }

  let level: 'low' | 'medium' | 'high' = 'low';
  let recommendation = 'طلب آمن وجاهز للتأكيد والشحن المباشر.';
  if (score >= 50) {
    level = 'high';
    recommendation = '⚠️ عالي الخطورة! يرجى عدم الشحن حتى الاتصال بالزبون والتحقق من العنوان أو حظر الطلب.';
  } else if (score >= 20) {
    level = 'medium';
    recommendation = 'طلب يحتاج إلى تأكيد هاتفي دقيق قبل إرسال الشحنة لشركة التوصيل.';
  }

  return { score: Math.min(100, score), level, reasons, recommendation };
}

